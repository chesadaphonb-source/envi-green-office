'use strict';

// Package the supplied PNG unchanged, without a separate image host or Drive permissions.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'assets/images/green-office-building.png'));
const signature = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]);
if (source.length < 24 || !source.subarray(0, 8).equals(signature) || source.toString('ascii', 12, 16) !== 'IHDR') {
  throw new Error('Hero image must be a PNG with image dimensions');
}
const width = source.readUInt32BE(16);
const height = source.readUInt32BE(20);
if (!width || !height) throw new Error('Hero image dimensions must be positive');
const markup = '<!-- Generated by scripts/build-hero-image.cjs from the supplied original PNG. -->\n' +
  '<img class="campus-art" src="data:image/png;base64,' + source.toString('base64') +
  '" width="' + width + '" height="' + height +
  '" alt="ภาพวาดอาคารคณะสิ่งแวดล้อม มหาวิทยาลัยเกษตรศาสตร์" decoding="async">\n';
fs.writeFileSync(path.join(root, 'hero-image.html'), markup, 'utf8');
console.log('Built hero-image.html from the original PNG (' + width + ' x ' + height + ', ' + source.length + ' bytes)');
