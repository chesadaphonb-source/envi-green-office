'use strict';

// Embed the supplied original image, unchanged, so Apps Script needs no image host.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'assets/images/KU copy.jpg'));
if (source[0] !== 0xff || source[1] !== 0xd8) throw new Error('Brand image must be JPEG');
const markup = '<!-- Generated by scripts/build-branding.cjs from the supplied JPEG. -->\n' +
  '<img class="institution-logo" src="data:image/jpeg;base64,' + source.toString('base64') +
  '" width="150" height="68" alt="มหาวิทยาลัยเกษตรศาสตร์ และคณะสิ่งแวดล้อม" decoding="async">\n';
fs.writeFileSync(path.join(root, 'branding.html'), markup, 'utf8');
console.log('Built branding.html from the original JPEG (' + source.length + ' bytes)');
